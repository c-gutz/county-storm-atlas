# imagecollection rather than just an image b/c time is involved, so its a stack of many images (different times)
era5_land = ee.ImageCollection("ECMWF/ERA5_LAND/MONTHLY_AGGR")
realtime = era5_land.select("temperature_2m","dewpoint_temperature_2m", "total_precipitation_sum", "volumetric_soil_water_layer_3")

counties = ee.FeatureCollection("TIGER/2018/Counties") \
  .filter(ee.Filter.lt("STATEFP", "60")) \
  .filter(ee.Filter.neq("STATEFP", "02")) \
  .filter(ee.Filter.neq("STATEFP", "15"))

# get the most recent month filed, which will be used for producing the anomalies below
month = realtime.sort("system:time_start", False).first().date().format("MM").getInfo()

# get only the three most recent months
realtime = realtime.sort("system:time_start", False).limit(3)
# uses the three month sum to get antecedent precip sum
precip_3mo = realtime.select("total_precipitation_sum").sum().rename("precip_prior3")
# only use the most recent month for the other 3 vals
latest = realtime.first().select([
    "temperature_2m","dewpoint_temperature_2m", "volumetric_soil_water_layer_3"
])
# combine precip_3mo and latest to get a single Image containing all 4 values
combined = latest.addBands(precip_3mo)

# reduceRegions calculates the average soil moisture of all the measurements in a given county and averages the monthly precipitation depth of all
# the county's measurements
# reduce_month is called across all images in the imagecollection
# for a given image: it uses reduceRegions to turn it into a featurecollection based around the counties
# since this doesnt keep track of the date metadata attached to the original image, must use map() to apply a function to every feature
# (county) giving it the date time associated with it
results = combined.reduceRegions(
    collection=counties,
    reducer=ee.Reducer.mean(),
    scale=11132,
    crs="EPSG:5070"
).select(["GEOID", "temperature_2m", "dewpoint_temperature_2m",
          "precip_prior3", "volumetric_soil_water_layer_3"]).map(lambda f: f.setGeometry(None)) # only pull the desired properties and drop geometry

# synchronous because the request is small and the cron job wont work with async easily
rows = results.getInfo()["features"]

data = [];
for row in rows:
  data.append(row["properties"])
df = pd.DataFrame(data)

clim = pd.read_parquet("/content/drive/MyDrive/Nino/cleaned_data/temp_humid_anomalies.parquet")

# create the temperature anomaly, comparing each county-month's temperature against that county and that month's average
for col in ["temperature_2m",	"dewpoint_temperature_2m"]:
  clim = clim[clim["cal_month"] == month]
  clim["GEOID"] = clim["GEOID"].astype(str).str.zfill(5)
  df = df.merge(clim[[col+"_normal", "GEOID"]], on=["GEOID"], how="left")
  df[col+"_anomaly"] = df[col] - df[col+"_normal"]
df.drop(columns=["dewpoint_temperature_2m", "temperature_2m", "temperature_2m_normal", "dewpoint_temperature_2m_normal"], inplace=True)
df

print(df["dewpoint_temperature_2m_anomaly"].describe())

# Replace Nantucket's empty values with Dukes County.
df.loc[df['GEOID'] == '25019', :] = df.loc[df['GEOID'] == '25007'].values

enso = pd.read_csv(("https://psl.noaa.gov/data/timeseries/month/data/nino34.long.anom.csv"))

enso = enso.rename(columns={'   NINA34  missing value -99.99 https://psl.noaa.gov/data/timeseries/month/': "nino_3.4"})
enso = enso[enso["nino_3.4"] > -99]
enso = enso.sort_values(by="Date", ascending=False)
current_enso = float(enso["nino_3.4"].iloc[0])
current_enso

import datetime
