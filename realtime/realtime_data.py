for row in df.to_dict("records"):
  key = row["GEOID"]
  realtime_json["counties"][key] = {
      "precip_3": float(row["precip_prior3"]),
      "soil": float(row["volumetric_soil_water_layer_3"]),
      "temp": float(row["temperature_2m_anomaly"]),
      "nino_3.4": current_enso
  }
realtime_json

